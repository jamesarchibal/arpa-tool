/**
 * Turn two sheets of ARPA's IOS v9 workbook into committed TypeScript fixtures.
 *
 * Why generate instead of reading the .xlsx from the test: the workbook lives in
 * /tmp, so a test that opens it passes on this machine today and fails after a
 * reboot or on CI. The fixtures are the contract, checked into git, and this
 * script is how you refresh them when Ignasi sends v10.
 *
 *   node scripts/ios-extract-fixtures.mjs [path-to-workbook.xlsx]
 *
 * Writes lib/ios/__fixtures__/vocabulary.ts and industries-oracle.ts.
 */
import * as fs from 'node:fs';
import { writeFileSync } from 'node:fs';
import XLSX from 'xlsx';

// The ESM build of SheetJS ships without a filesystem, so readFile throws
// "Cannot access file" until you hand it one. The CJS build wires this itself,
// which is why `require('xlsx')` works and a plain `import` does not.
XLSX.set_fs(fs);

const file =
  process.argv[2] ?? '/tmp/arpaios/PE_Airtable_Projects_Build_Workbook_v9.xlsx';
const out = new URL('../lib/ios/__fixtures__/', import.meta.url);

const wb = XLSX.readFile(file);

/**
 * Every sheet carries two preamble rows (a title, then a "Mirror of
 * build-pack/..." note), so the real header is the third. Asserting the first
 * header cell means a changed preamble in v10 fails loudly here instead of
 * silently loading the header row as data.
 */
function rows(sheet, firstHeader) {
  const grid = XLSX.utils.sheet_to_json(wb.Sheets[sheet], {
    header: 1,
    blankrows: false,
  });
  const header = grid[2]?.map((h) => String(h).trim());
  if (header?.[0] !== firstHeader) {
    throw new Error(
      `${sheet}: expected first header "${firstHeader}", got "${header?.[0]}". The sheet layout changed.`,
    );
  }
  return grid
    .slice(3)
    .map((r) => Object.fromEntries(header.map((k, i) => [k, r[i] ?? ''])));
}

// ---------------------------------------------------------------- vocabulary

const vocab = new Map();
for (const r of rows('Vocabulary', 'List')) {
  const list = String(r.List).trim();
  if (!list) continue;
  if (!vocab.has(list)) vocab.set(list, []);
  vocab.get(list).push(String(r.Option).trim());
}

writeFileSync(
  new URL('vocabulary.ts', out),
  `// GENERATED by scripts/ios-extract-fixtures.mjs. Do not edit by hand.
//
// The 'Vocabulary' sheet of ARPA's IOS v9 workbook: every single-select option,
// verbatim. lib/ios/lists.test.ts compares our exported lists against this, so a
// dropped option or a smart dash becomes a failed test and not a failed insert.

export const VOCABULARY: Record<string, readonly string[]> = ${JSON.stringify(
    Object.fromEntries(vocab),
    null,
    2,
  )};
`,
);

// ---------------------------------------------------------- industries oracle

/** The 8 rated criteria, in the sheet's own column order. */
const CRITERIA = [
  'Market Growth',
  'Fragmentation / Add-ons',
  'Target Density',
  'Margin Profile',
  'Recurring / Resilient Revenue',
  'Barriers / Differentiation',
  'Succession / Founder Exit',
  'Risk (5 = low)',
];

const oracle = rows('Seed_Industries', 'Subsector').map((r) => ({
  subsector: String(r.Subsector).trim(),
  ratings: CRITERIA.map((c) => Number(r[c])),
  // Their own answers. The whole point: we never import these, we assert against them.
  score: Number(r['Check: Weighted Score (source)']),
  tier: String(r['Check: Tier (source)']).trim().charAt(0),
}));

writeFileSync(
  new URL('industries-oracle.ts', out),
  `// GENERATED by scripts/ios-extract-fixtures.mjs. Do not edit by hand.
//
// The 100 subsectors of ARPA's 'Seed_Industries' sheet with their 8 ratings, plus
// the sheet's own 'Check: Weighted Score' and 'Check: Tier' columns. Those two are
// the oracle for lib/ios/industries.ts: we derive score and tier in TypeScript and
// they have to come out equal to ARPA's numbers on all 100 rows.

export interface OracleRow {
  subsector: string;
  /** Market Growth, Fragmentation / Add-ons, Target Density, Margin Profile, Recurring / Resilient Revenue, Barriers / Differentiation, Succession / Founder Exit, Risk (5 = low). */
  ratings: number[];
  score: number;
  tier: string;
}

export const INDUSTRIES_ORACLE: OracleRow[] = ${JSON.stringify(oracle, null, 2)};
`,
);

console.log(
  `vocabulary.ts: ${vocab.size} lists, ${[...vocab.values()].reduce((n, v) => n + v.length, 0)} options`,
);
console.log(`industries-oracle.ts: ${oracle.length} subsectors`);
